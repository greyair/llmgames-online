export type IconName = keyof typeof glyphs;

export const iconNames = Object.keys(glyphs).filter((name): name is IconName =>
  Object.hasOwn(glyphs, name),
);

const paths = new Map<IconName, string>();

function glyphPath(name: IconName) {
  let path = paths.get(name);

  if (path) return path;
  path = "";
  glyphs[name].forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== "#") continue;
      let end = x;

      while (row[end + 1] === "#") end++;
      path += `M${x} ${y}h${end - x + 1}v1h${-(end - x + 1)}z`;
      x = end;
    }
  });
  paths.set(name, path);

  return path;
}

export function Icon({
  name,
  size = 18,
  className,
  ...props
}: Omit<SVGProps<SVGSVGElement>, "ref"> & { name: IconName; size?: number }) {
  const cell = Math.max(1, Math.round(size / 9));
  const px = cell * 9;

  return (
    <svg
      aria-hidden="true"
      viewBox="0 0 9 9"
      width={px}
      height={px}
      {...{ "shapeRendering": "crispEdges" }}
      fill="currentColor"
      className={["ui-icon", className].filter(Boolean).join(" ")}
      {...props}
    >
      <path d={glyphPath(name)} />
    </svg>
  );
}
