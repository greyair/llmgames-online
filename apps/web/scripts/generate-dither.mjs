// Writes src/design/dither-masks.css: Bayer 4x4 and 8x8 threshold masks as
// SVG data URIs, so CSS can draw ordered-dither tones without WebGL.
// Run: node scripts/generate-dither.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const bayer4 = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];

const bayer8 = [
  0, 32, 8, 40, 2, 34, 10, 42, 48, 16, 56, 24, 50, 18, 58, 26, 12, 44, 4, 36, 14, 46, 6, 38, 60, 28,
  52, 20, 62, 30, 54, 22, 3, 35, 11, 43, 1, 33, 9, 41, 51, 19, 59, 27, 49, 17, 57, 25, 15, 47, 7,
  39, 13, 45, 5, 37, 63, 31, 55, 23, 61, 29, 53, 21,
];

function mask(matrix, size, level, levels) {
  let rects = "";

  for (let i = 0; i < matrix.length; i++)
    if (matrix[i] < (level * matrix.length) / levels)
      rects += `<rect x='${i % size}' y='${Math.floor(i / size)}' width='1' height='1'/>`;
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${size} ${size}' shape-rendering='crispEdges'>${rects}</svg>`;

  return `url("data:image/svg+xml,${svg.replace(/</g, "%3C").replace(/>/g, "%3E")}")`;
}

// A 4-cell-wide strip whose coverage climbs from 0 to 100% over `length` cells.
function ramp(length, vertical, rising) {
  let rects = "";

  for (let step = 0; step < length; step++) {
    const coverage = (rising ? step + 0.5 : length - step - 0.5) / length;

    for (let cross = 0; cross < 4; cross++) {
      const [x, y] = vertical ? [cross, step] : [step, cross];

      if (bayer4[(y % 4) * 4 + (x % 4)] < coverage * 16)
        rects += `<rect x='${x}' y='${y}' width='1' height='1'/>`;
    }
  }

  const [w, h] = vertical ? [4, length] : [length, 4];
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${w} ${h}' shape-rendering='crispEdges'>${rects}</svg>`;

  return `url("data:image/svg+xml,${svg.replace(/</g, "%3C").replace(/>/g, "%3E")}")`;
}

const lines = [
  "/* Generated by scripts/generate-dither.mjs. Do not edit by hand.",
  "   --bayer-N covers N/16 of each 4x4 cell; --bayer8-N covers N/16 of each 8x8 cell.",
  "   --ramp-* are 4-cell strips that fade over 24 cells (48px at --px:2px). */",
  ":root {",
];

for (let level = 1; level < 16; level++)
  lines.push(` --bayer-${level}:${mask(bayer4, 4, level, 16)};`);

for (let level = 1; level < 16; level++)
  lines.push(` --bayer8-${level}:${mask(bayer8, 8, level, 16)};`);

lines.push(
  ` --ramp-down:${ramp(24, true, false)};`,
  ` --ramp-up:${ramp(24, true, true)};`,
  ` --ramp-right:${ramp(24, false, false)};`,
  ` --ramp-left:${ramp(24, false, true)};`,
);

lines.push("}", "");

writeFileSync(
  fileURLToPath(new URL("../src/design/dither-masks.css", import.meta.url)),
  lines.join("\n"),
);
